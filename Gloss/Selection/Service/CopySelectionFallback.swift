import Foundation
import AppKit
import os

/// Reads a selection the app doesn't expose through Accessibility: presses the app's Copy menu item, reads the
/// pasteboard and puts the previous clipboard back.
@MainActor
internal final class CopySelectionFallback {
    // MARK: - Properties

    private let reader: AccessibilityReader
    private let pasteboard: NSPasteboard

    /// Copying in these would put files or Dock items on the pasteboard, not text.
    private static let deniedBundleIDs: Set<String> = ["com.apple.finder", "com.apple.dock"]
    private static let maximumSnapshotBytes = 10 * 1024 * 1024
    private static let pollInterval = Duration.milliseconds(15)
    private static let copyTimeout = Duration.milliseconds(300)
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let logger = Logger.gloss("CopySelectionFallback")

    // MARK: - Lifecycle

    internal init(reader: AccessibilityReader, pasteboard: NSPasteboard = .general) {
        self.reader = reader
        self.pasteboard = pasteboard
    }

    // MARK: - Actions

    /// Has the app copy its selection, reads it and restores the previous clipboard.
    ///
    /// Runs only when macOS always allows Gloss to read the pasteboard, so the paste alert never interrupts reading.
    /// - Parameters:
    ///   - processID: The app with the selection.
    ///   - bundleID: Its bundle identifier.
    /// - Returns: The copied text, or `nil` when nothing was copied or the fallback isn't allowed here.
    /// - Throws: `CancellationError` when a newer press superseded this one (the clipboard is restored first).
    internal func copySelection(processID: pid_t, bundleID: String?) async throws -> String? {
        guard pasteboard.allowsReadingWithoutAlert else {
            Self.logger.debug("Copy fallback skipped: clipboard reading isn't always allowed")
            return nil
        }
        if let bundleID, Self.deniedBundleIDs.contains(bundleID) {
            return nil
        }
        guard let snapshot = PasteboardSnapshot.capture(pasteboard, maximumBytes: Self.maximumSnapshotBytes) else {
            Self.logger.debug("Copy fallback skipped: the clipboard holds too much data to restore")
            return nil
        }
        let previousChangeCount = pasteboard.changeCount
        try Task.checkCancellation()
        guard await reader.pressCopyMenuItem(processID: processID) else { return nil }

        // Once the app was asked to copy, finish waiting and restoring even if this capture gets cancelled, so the
        // user's clipboard is never left replaced. Awaiting an unstructured task doesn't forward cancellation.
        let text = await Task { @MainActor in
            await self.collectCopiedText(after: previousChangeCount, restoring: snapshot)
        }.value
        try Task.checkCancellation()
        return text
    }

    // MARK: - Private

    private func collectCopiedText(after previousChangeCount: Int, restoring snapshot: PasteboardSnapshot) async -> String? {
        let clock = ContinuousClock()
        let deadline = clock.now + Self.copyTimeout
        while pasteboard.changeCount == previousChangeCount, clock.now < deadline {
            do {
                try await Task.sleep(for: Self.pollInterval)
            } catch {
                // Only cancellation throws, and nothing cancels this task; stop waiting if it ever happens.
                break
            }
        }
        let copiedChangeCount = pasteboard.changeCount
        guard copiedChangeCount != previousChangeCount else {
            Self.logger.debug("Copy fallback: the app copied nothing")
            return nil
        }
        let types = pasteboard.types ?? []
        // Finder-like selections put files on the pasteboard; their names aren't text to translate.
        let text = types.contains(.fileURL) ? nil : pasteboard.string(forType: .string)
        // Restore only if nothing else wrote to the clipboard after the app's copy.
        if pasteboard.changeCount == copiedChangeCount {
            snapshot.restore(to: pasteboard, marker: Self.autoGeneratedType)
        }
        return text
    }
}
