import Foundation
import AppKit

/// Every item and type on a pasteboard, to put back after a temporary write.
internal struct PasteboardSnapshot: Equatable, Sendable {
    /// One representation of an item. Order matters: the first type is the richest one.
    internal struct Entry: Equatable, Sendable {
        internal var type: String
        internal var data: Data
    }

    internal var items: [[Entry]]

    // MARK: - Capture

    /// Copies everything on a pasteboard.
    /// - Parameters:
    ///   - pasteboard: The pasteboard to read.
    ///   - maximumBytes: Gives up above this size; reading forces promised data (large images, files) to render.
    /// - Returns: The snapshot, or `nil` when the contents are too large.
    @MainActor
    internal static func capture(_ pasteboard: NSPasteboard, maximumBytes: Int) -> PasteboardSnapshot? {
        var total = 0
        var items: [[Entry]] = []
        for item in pasteboard.pasteboardItems ?? [] {
            var entries: [Entry] = []
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                guard total <= maximumBytes else { return nil }
                entries.append(Entry(type: type.rawValue, data: data))
            }
            items.append(entries)
        }
        return PasteboardSnapshot(items: items)
    }

    // MARK: - Restore

    /// Replaces a pasteboard's contents with the snapshot.
    /// - Parameters:
    ///   - pasteboard: The pasteboard to write.
    ///   - marker: Empty extra type for the first item, e.g. `org.nspasteboard.AutoGeneratedType`, which tells
    ///     clipboard managers not to record the restore as a new copy.
    @MainActor
    internal func restore(to pasteboard: NSPasteboard, marker: NSPasteboard.PasteboardType? = nil) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        let restored = items.enumerated().map { index, entries in
            let item = NSPasteboardItem()
            for entry in entries {
                item.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type))
            }
            if index == 0, let marker {
                item.setData(Data(), forType: marker)
            }
            return item
        }
        pasteboard.writeObjects(restored)
    }
}
