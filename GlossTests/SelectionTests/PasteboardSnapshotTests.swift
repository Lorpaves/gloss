import Foundation
import AppKit
import Testing
@testable import Gloss

/// Uses private named pasteboards, which pasteboard privacy doesn't restrict.
@MainActor
struct PasteboardSnapshotTests {
    private static let customType = NSPasteboard.PasteboardType("com.lorpaves.gloss.tests.custom")
    private static let marker = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    @Test func testRestorePutsBackEveryTypeOfAnItem() throws {
        let restored = try restoredContents()
        #expect(restored.firstString == "Hello")
        #expect(restored.firstHTML == "<b>Hello</b>")
    }

    @Test func testRestorePutsBackEveryItem() throws {
        let restored = try restoredContents()
        #expect(restored.itemCount == 2)
        #expect(restored.lastCustomData == Data([1, 2, 3]))
    }

    @Test func testRestoreMarksTheClipboardAsAutoGenerated() throws {
        let restored = try restoredContents()
        #expect(restored.isMarked)
    }

    @Test func testEmptyClipboardStaysEmptyAfterRestore() throws {
        let pasteboard = makePasteboard()
        defer { pasteboard.releaseGlobally() }

        let snapshot = try #require(PasteboardSnapshot.capture(pasteboard, maximumBytes: 1_000_000))
        pasteboard.setString("Copied selection", forType: .string)
        snapshot.restore(to: pasteboard, marker: Self.marker)

        #expect(pasteboard.pasteboardItems?.isEmpty ?? true)
    }

    @Test func testCaptureRefusesContentsLargerThanTheLimit() {
        let pasteboard = makePasteboard()
        defer { pasteboard.releaseGlobally() }
        pasteboard.setData(Data(count: 100), forType: Self.customType)

        #expect(PasteboardSnapshot.capture(pasteboard, maximumBytes: 10) == nil)
    }

    // MARK: - Private

    /// What a pasteboard holds after a restore; read before the pasteboard is released, because
    /// `NSPasteboardItem` data is fetched lazily from the pasteboard server.
    private struct RestoredContents {
        var itemCount: Int
        var firstString: String?
        var firstHTML: String?
        var isMarked: Bool
        var lastCustomData: Data?
    }

    /// Two items on a fresh pasteboard, replaced by a "copied selection", then restored from a snapshot.
    private func restoredContents() throws -> RestoredContents {
        let pasteboard = makePasteboard()
        defer { pasteboard.releaseGlobally() }
        let first = NSPasteboardItem()
        first.setString("Hello", forType: .string)
        first.setString("<b>Hello</b>", forType: .html)
        let second = NSPasteboardItem()
        second.setData(Data([1, 2, 3]), forType: Self.customType)
        pasteboard.writeObjects([first, second])

        let snapshot = try #require(PasteboardSnapshot.capture(pasteboard, maximumBytes: 1_000_000))
        pasteboard.clearContents()
        pasteboard.setString("Copied selection", forType: .string)
        snapshot.restore(to: pasteboard, marker: Self.marker)

        let items = pasteboard.pasteboardItems ?? []
        return RestoredContents(
            itemCount: items.count,
            firstString: items.first?.string(forType: .string),
            firstHTML: items.first?.string(forType: .html),
            isMarked: items.first?.types.contains(Self.marker) ?? false,
            lastCustomData: items.last?.data(forType: Self.customType)
        )
    }

    private func makePasteboard() -> NSPasteboard {
        let pasteboard = NSPasteboard(name: NSPasteboard.Name("GlossTests-\(UUID().uuidString)"))
        pasteboard.clearContents()
        return pasteboard
    }
}
